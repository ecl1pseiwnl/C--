const int N = 3008;
int dp[N][N];

signed main() {
    cin.tie(nullptr)->sync_with_stdio(false);
    string s,t;
    cin >> s >> t;
    int n = s.size(), m = t.size();
    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= m; j++) {
            if (s[i-1] == t[j-1]) {
                dp[i][j] = dp[i-1][j-1] + 1;
            } else dp[i][j] = max(dp[i-1][j],dp[i][j-1]);
        }
    }
    string k = "";
    while(n && m) {
        if (s[n-1] == t[m-1]) {
            k += s[n-1];
            n--;
            m--;
        } else if (dp[n-1][m] > dp[n][m-1]) {
            n--;
        } else m--;
    }
    reverse(all(k));
    cout << k;
    cerr << "\nTime elapsed: " << TIME << "s. \n";
    return 0;
}
