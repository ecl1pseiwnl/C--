void bt(int i) {
    for (int j = 0; j < s.size(); j++) {
        if (!u[j]) {
            a[i] = s[j];
            u[j] = 1;
            if (i == s.size()-1) {
                p();
            }
            else bt(i+1);
            u[j] = 0;
        }
    }
}

